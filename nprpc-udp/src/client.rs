//! A blocking client, talking to a single server

use std::{
    io,
    net::{Ipv4Addr, Ipv6Addr, SocketAddr, UdpSocket},
    num::Wrapping,
    time::Duration,
};

use nprpc::io::{
    Storage,
    client::{Backend, Io},
};

/// A UDP socket connected to a server, used as a client [`Io`].
#[derive(Debug)]
pub struct ConnectedUdpSocket(UdpSocket);

impl ConnectedUdpSocket {
    /// Wraps a socket that's already [connected](UdpSocket::connect) to the
    /// server.
    pub fn new(socket: UdpSocket) -> Self {
        Self(socket)
    }

    /// Returns the underlying socket.
    pub fn socket(&self) -> &UdpSocket {
        &self.0
    }

    /// Unwraps the underlying socket.
    pub fn into_inner(self) -> UdpSocket {
        self.0
    }
}

impl Io for ConnectedUdpSocket {
    type Error = io::Error;

    fn send_then_receive_raw_frames<'a>(
        &mut self,
        outgoing: &[u8],
        incoming: &'a mut [u8],
    ) -> Result<&'a [u8], Self::Error> {
        self.0.send(outgoing)?;
        let used = self.0.recv(incoming)?;
        Ok(&incoming[..used])
    }
}

/// A client [`Backend`] that makes requests to one server over UDP
///
/// `UdpClient` implements the `Client` traits generated by
/// [`nprpc::interface!`], so methods can be called on it directly.
///
/// No read timeout is set by default, so a lost request or response will
/// block forever. See [`UdpClient::set_timeout()`].
#[derive(Debug)]
pub struct UdpClient<S> {
    seqno: Wrapping<u16>,
    storage: S,
    socket: ConnectedUdpSocket,
}

impl<S: Storage> UdpClient<S> {
    /// Connects to the server at `target`.
    ///
    /// The OS picks the local address and port, in the same address family
    /// as `target`.
    pub fn connect(target: SocketAddr, storage: S) -> io::Result<Self> {
        let local: SocketAddr = match target {
            SocketAddr::V4(_) => (Ipv4Addr::UNSPECIFIED, 0).into(),
            SocketAddr::V6(_) => (Ipv6Addr::UNSPECIFIED, 0).into(),
        };
        let socket = UdpSocket::bind(local)?;
        socket.connect(target)?;
        Ok(Self::from_socket(socket, storage))
    }

    /// Uses a socket that's already [connected](UdpSocket::connect) to the
    /// server.
    pub fn from_socket(socket: UdpSocket, storage: S) -> Self {
        Self {
            seqno: Wrapping(0),
            storage,
            socket: ConnectedUdpSocket::new(socket),
        }
    }

    /// Sets how long to wait for each response, or `None` to wait forever.
    ///
    /// A request that times out fails with an I/O error, which can be
    /// recognized with [`is_timeout()`](crate::is_timeout).
    pub fn set_timeout(&self, timeout: Option<Duration>) -> io::Result<()> {
        self.socket.0.set_read_timeout(timeout)
    }

    /// Returns the underlying socket.
    pub fn socket(&self) -> &UdpSocket {
        self.socket.socket()
    }

    /// Returns the request and response storage.
    pub fn storage(&self) -> &S {
        &self.storage
    }

    /// Returns the request and response storage, mutably.
    pub fn storage_mut(&mut self) -> &mut S {
        &mut self.storage
    }
}

impl<S: Storage> Backend for UdpClient<S> {
    type Storage = S;
    type Io = ConnectedUdpSocket;

    fn next_sequence_number(&mut self) -> u16 {
        let now = self.seqno;
        self.seqno += 1;
        now.0
    }

    fn parts(&mut self) -> (&mut Self::Storage, &mut Self::Io) {
        let Self {
            seqno: _,
            storage,
            socket,
        } = self;
        (storage, socket)
    }
}
