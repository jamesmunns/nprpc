//! A blocking UDP server.

use std::{
    io,
    net::{SocketAddr, ToSocketAddrs, UdpSocket},
    time::Duration,
};

use nprpc::{
    ServerIoError,
    io::{
        Storage,
        server::{Backend, Io, RawIoFrame},
    },
};

use crate::is_timeout;

/// A bound UDP socket, used as a server [`Io`]
///
/// If the socket has a read timeout, timeouts are not treated as errors and
/// `serve_one` returns [`Served::Idle`](nprpc::Served::Idle).
#[derive(Debug)]
pub struct BoundUdpSocket(UdpSocket);

impl BoundUdpSocket {
    /// Wraps a bound socket.
    pub fn new(socket: UdpSocket) -> Self {
        Self(socket)
    }

    /// Returns the underlying socket.
    pub fn socket(&self) -> &UdpSocket {
        &self.0
    }

    /// Unwraps the underlying socket.
    pub fn into_inner(self) -> UdpSocket {
        self.0
    }
}

impl Io for BoundUdpSocket {
    type Error = io::Error;
    type Meta = SocketAddr;

    fn recv_one_frame_raw<'data>(
        &mut self,
        incoming: &'data mut [u8],
    ) -> Result<Option<RawIoFrame<'data, Self::Meta>>, ServerIoError<Self::Error>> {
        match self.0.recv_from(incoming) {
            Ok((used, peer)) => Ok(Some(RawIoFrame {
                meta: peer,
                raw: &incoming[..used],
            })),
            Err(e) if is_timeout(&e) => Ok(None),
            Err(e) => Err(ServerIoError::Io(e)),
        }
    }

    fn send_one_frame_raw(
        &mut self,
        outgoing: RawIoFrame<'_, Self::Meta>,
    ) -> Result<(), ServerIoError<Self::Error>> {
        self.0
            .send_to(outgoing.raw, outgoing.meta)
            .map(drop)
            .map_err(ServerIoError::Io)
    }
}

/// A server [`Backend`] that serves requests over UDP
///
/// Pass it to the `Server::serve_one` method generated by
/// [`nprpc::interface!`] or [`nprpc::compose_interfaces!`].
///
/// No read timeout is set by default, so `serve_one` blocks until a request
/// arrives. See [`UdpServer::set_timeout()`].
#[derive(Debug)]
pub struct UdpServer<S> {
    storage: S,
    socket: BoundUdpSocket,
}

impl<S: Storage> UdpServer<S> {
    /// Binds a socket to `addr` to serve requests.
    pub fn bind(addr: impl ToSocketAddrs, storage: S) -> io::Result<Self> {
        Ok(Self::from_socket(UdpSocket::bind(addr)?, storage))
    }

    /// Uses an already bound socket.
    pub fn from_socket(socket: UdpSocket, storage: S) -> Self {
        Self {
            storage,
            socket: BoundUdpSocket::new(socket),
        }
    }

    /// Sets how long to wait for each request, or `None` to wait forever.
    ///
    /// When no request arrives in time, `serve_one` returns
    /// [`Served::Idle`](nprpc::Served::Idle), e.g. so the server can check
    /// whether it should stop.
    pub fn set_timeout(&self, timeout: Option<Duration>) -> io::Result<()> {
        self.socket.0.set_read_timeout(timeout)
    }

    /// Returns the underlying socket.
    pub fn socket(&self) -> &UdpSocket {
        self.socket.socket()
    }

    /// Returns the request and response storage.
    pub fn storage(&self) -> &S {
        &self.storage
    }

    /// Returns the request and response storage, mutably.
    pub fn storage_mut(&mut self) -> &mut S {
        &mut self.storage
    }
}

impl<S: Storage> Backend for UdpServer<S> {
    type Storage = S;
    type Io = BoundUdpSocket;

    fn parts(&mut self) -> (&mut Self::Storage, &mut Self::Io) {
        let Self { storage, socket } = self;
        (storage, socket)
    }
}
